# Makes a "chip voice" sample for the TX sound board from Windows' own text-to-speech:
# 8 kHz, silence trimmed, normalized, pre-emphasized (FM radios de-emphasize), 4 bits
# signed (-8..7), two samples per byte, low nibble first. Writes a C header.
#
#   tools\make_voice.ps1                        "hello" -> src\voice_hello.h
#   tools\make_voice.ps1 -Text "hi there" -Name hi
param(
  [string]$Text = 'hello',
  [string]$Name = 'hello',
  [int]$Rate = -1                                  # speech rate, -10..10
)
$ErrorActionPreference = 'Stop'
$repo = Split-Path $PSScriptRoot -Parent
Add-Type -AssemblyName System.Speech

# 1. speak into memory as 8 kHz 16-bit mono PCM
$fmt = New-Object System.Speech.AudioFormat.SpeechAudioFormatInfo 8000, 'Sixteen', 'Mono'
$ms = New-Object System.IO.MemoryStream
$tts = New-Object System.Speech.Synthesis.SpeechSynthesizer
$tts.Rate = $Rate
$tts.SetOutputToAudioStream($ms, $fmt)
$tts.Speak($Text)
$tts.Dispose()
$b = $ms.ToArray()
$n = [int]($b.Length / 2)
$s = New-Object 'int[]' $n
for ($i = 0; $i -lt $n; $i++) { $s[$i] = [BitConverter]::ToInt16($b, $i * 2) }

# 2. trim the silence at both ends
$lim = 600
$a = 0; while ($a -lt $n - 1 -and [Math]::Abs($s[$a]) -lt $lim) { $a++ }
$z = $n - 1; while ($z -gt $a -and [Math]::Abs($s[$z]) -lt $lim) { $z-- }
$a = [Math]::Max(0, $a - 80); $z = [Math]::Min($n - 1, $z + 80)

# 3. pre-emphasis y = x - 0.7 x[-1], then scale the loudest to full 4-bit range
$len = $z - $a + 1
$y = New-Object 'double[]' $len
$prev = 0.0; $peak = 1.0
for ($i = 0; $i -lt $len; $i++) {
  $x = [double]$s[$a + $i]
  $y[$i] = $x - 0.7 * $prev; $prev = $x
  if ([Math]::Abs($y[$i]) -gt $peak) { $peak = [Math]::Abs($y[$i]) }
}
$q = New-Object 'int[]' $len
for ($i = 0; $i -lt $len; $i++) {
  $q[$i] = [Math]::Max(-8, [Math]::Min(7, [int][Math]::Round($y[$i] * 8.5 / $peak)))
}

# 4. pack and write
$nb = [int][Math]::Ceiling($len / 2)
$lines = @()
for ($i = 0; $i -lt $nb; $i += 16) {
  $row = @()
  for ($j = $i; $j -lt [Math]::Min($nb, $i + 16); $j++) {
    $lo = $q[2 * $j] -band 15
    $hi = if (2 * $j + 1 -lt $len) { $q[2 * $j + 1] -band 15 } else { 0 }
    $row += ('0x{0:x2}' -f ($lo -bor ($hi -shl 4)))
  }
  $lines += '  ' + ($row -join ',') + ','
}
$up = $Name.ToUpper()
$out = @(
  "// Generated by tools/make_voice.ps1 from Windows text-to-speech: `"$Text`"",
  "// 8 kHz, 4-bit signed, two samples per byte (low nibble first). $len samples, $([Math]::Round($len / 8.0)) ms.",
  '#pragma once',
  "static const uint32_t VOICE_${up}_N = $len;",
  "static const uint8_t VOICE_${up}[] = {"
) + $lines + '};'
$path = Join-Path $repo "src\voice_$Name.h"
[IO.File]::WriteAllLines($path, $out)
Write-Output ("{0}: {1} samples, {2} ms, {3} bytes" -f $path, $len, [Math]::Round($len / 8.0), $nb)
